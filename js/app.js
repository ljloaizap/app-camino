  function initCredential() {
    const spread = document.getElementById('spread');
    const prev = document.getElementById('pager-prev');
    const next = document.getElementById('pager-next');
    const nextHint = next.querySelector('[data-label]');
    const status = document.getElementById('pager-status');
    const desktop = window.matchMedia('(min-width: 900px)');
    const total = C.leaves.length;

    const step = () => (desktop.matches ? 2 : 1);
    const normalize = (i) => {
      const clamped = Math.max(0, Math.min(total - 1, i));
      return desktop.matches ? clamped - (clamped % 2) : clamped;
    };

    let current = normalize((parseInt(param('leaf'), 10) || 1) - 1);

    function render(animate) {
      const shown = desktop.matches ? [current, current + 1] : [current];
      spread.replaceChildren(...shown.map((i) => (i < total ? leaf(i) : blankLeaf())));
      C.art.hydrate(spread);

      const isLast = current + step() >= total;
      prev.disabled = current === 0;
      const nextLabel = isLast ? 'Dedicatoria' : 'Siguiente';
      if (nextHint) nextHint.textContent = nextLabel;
      next.setAttribute('aria-label', isLast ? 'Ir a la dedicatoria' : 'Hoja siguiente');
      prev.setAttribute('aria-label', current === 0 ? 'Primera hoja' : 'Hoja anterior');

      const last = Math.min(current + step(), total);
      status.textContent =
        last - current > 1 ? `Hojas ${current + 1}–${last} de ${total}` : `Hoja ${current + 1} de ${total}`;

      window.history.replaceState(null, '', `?leaf=${current + 1}`);
      sessionStorage.setItem(LEAF_KEY, String(current + 1));
      if (animate) animateIn(spread);
    }

    prev.addEventListener('click', () => {
      current = normalize(current - step());
      render(true);
    });

    next.addEventListener('click', () => {
      if (current + step() >= total) {
        navigate('dedication.html', true);
        return;
      }
      current = normalize(current + step());
      render(true);
    });

    const onViewportChange = () => {
      current = normalize(current);
      render(false);
    };
    desktop.addEventListener('change', onViewportChange);

    const book = document.querySelector('.credential__book');
    const unswipe = bindSwipe(
      book,
      () => {
        if (!prev.disabled) prev.click();
      },
      () => next.click()
    );

    render(false);
    return () => {
      desktop.removeEventListener('change', onViewportChange);
      unswipe();
    };
  }

