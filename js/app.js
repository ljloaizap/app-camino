  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
  const ROMAN = ['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII'];

  const pad = (n) => String(n).padStart(2, '0');
  const param = (name) => new URLSearchParams(window.location.search).get(name);

  function htmlEl(tag, props, html) {
    const node = el(tag, props);
    node.innerHTML = html;
    return node;
  }

  function el(tag, props, children) {
    const node = document.createElement(tag);
    if (props) {
      Object.entries(props).forEach(([key, value]) => {
        if (value == null || value === false) return;
        if (key === 'class') node.className = value;
        else if (key === 'text') node.textContent = value;
        // Only for SVG markup generated by art.js.
        else if (key === 'svg') node.innerHTML = value;
        else node.setAttribute(key, value === true ? '' : value);
      });
    }
    (children || []).forEach((child) => {
      if (child == null) return;
      node.append(child instanceof Node ? child : document.createTextNode(String(child)));
    });
    return node;
  }

  /* ---------- Data ---------- */

  function chapterOf(id) {
    const index = C.chapters.findIndex((ch) => ch.stamps.includes(id));
    return index === -1
      ? { title: 'Capítulo pendiente', number: '' }
      : { title: C.chapters[index].title, number: ROMAN[index] || String(index + 1) };
  }

  function leafOf(id) {
    const index = C.leaves.findIndex((page) => page.includes(id));
    return index === -1 ? 0 : index;
  }

  const LEAF_KEY = 'camino.credentialLeaf';

  function parseLeafNumber(value) {
    const n = parseInt(value, 10);
    return Number.isInteger(n) && n >= 1 ? n : null;
  }

  function credentialLeafForReturn(stampId) {
    return (
      parseLeafNumber(param('fromLeaf')) ||
      parseLeafNumber(sessionStorage.getItem(LEAF_KEY)) ||
      leafOf(stampId) + 1
    );
  }

  function credentialHref(stampId) {
    return `credential.html?leaf=${credentialLeafForReturn(stampId)}`;
  }

  function stampHref(id) {
    const fromLeaf = parseLeafNumber(param('fromLeaf'));
    return fromLeaf ? `stamp.html?id=${id}&fromLeaf=${fromLeaf}` : `stamp.html?id=${id}`;
  }

  function getStamp(id) {
    const meta = C.catalogMeta && C.catalogMeta(id);
    if (!meta) return { id, status: 'pending', title: 'Este sello no existe' };

    const title =
      C.isPendingTitle && C.isPendingTitle(meta.title) ? 'Contenido pendiente' : meta.title;
    const page = C.stampPages && C.stampPages[id];
    const motif = C.art.motifForStamp(meta);

    if (page && page.status === 'ready') {
      const stamp = Object.assign({ id, title, status: 'ready' }, page);
      if (stamp.layout === 'day' && !stamp.heading) stamp.heading = title;
      const pageArt = stamp.art || {};
      stamp.art = Object.assign({}, motif, pageArt, {
        bottom: pageArt.bottom === 'Sello' ? `Sello ${pad(id)}` : pageArt.bottom || motif.bottom,
      });
      return stamp;
    }

    const ratios = ['landscape', 'portrait', 'square', 'panorama'];
    return {
      id,
      title,
      status: 'ready',
      layout: 'stub',
      art: motif,
      photo: {
        src: null,
        alt: '',
        ratio: ratios[(id - 1) % ratios.length],
        label: 'Fotografía',
      },
      body: '[Contenido pendiente]',
    };
  }

  const rotation = (id) => ((id * 37) % 11) - 5;

