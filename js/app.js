(function () {
  'use strict';
  const C = window.CAMINO;
  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
  const ROMAN = ['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII'];

  const pad = (n) => String(n).padStart(2, '0');
  const param = (name) => new URLSearchParams(window.location.search).get(name);

  function el(tag, props, children) {
    const node = document.createElement(tag);
    if (props) {
      Object.entries(props).forEach(([key, value]) => {
        if (value == null || value === false) return;
        if (key === 'class') node.className = value;
        else if (key === 'text') node.textContent = value;
        // Only for SVG markup generated by art.js.
        else if (key === 'svg') node.innerHTML = value;
        else node.setAttribute(key, value === true ? '' : value);
      });
    }
    (children || []).forEach((child) => {
      if (child == null) return;
      node.append(child instanceof Node ? child : document.createTextNode(String(child)));
    });
    return node;
  }

  /* ---------- Data ---------- */

  function chapterOf(id) {
    const index = C.chapters.findIndex((ch) => ch.stamps.includes(id));
    return index === -1
      ? { title: 'Capítulo pendiente', number: '' }
      : { title: C.chapters[index].title, number: ROMAN[index] || String(index + 1) };
  }

  function leafOf(id) {
    const index = C.leaves.findIndex((page) => page.includes(id));
    return index === -1 ? 0 : index;
  }

  function getStamp(id) {
    const data = C.stamps[id];
    if (data && data.status === 'ready') return Object.assign({ id }, data);
    return { id, status: 'pending', title: 'Contenido pendiente' };
  }

  const rotation = (id) => ((id * 37) % 11) - 5;

  /* ---------- Components ---------- */

  function photo(p, extraClass) {
    const fig = el('figure', { class: `photo photo--${p.ratio || 'landscape'}${extraClass ? ` ${extraClass}` : ''}` });
    if (p.src) {
      fig.append(el('img', { src: p.src, alt: p.alt || '', loading: 'lazy', decoding: 'async' }));
    } else {
      fig.append(
        el('div', { class: 'photo__ph', role: 'img', 'aria-label': `Espacio para fotografía: ${p.label || ''}` }, [
          el('span', { class: 'photo__ph-label', text: p.label || 'Fotografía' }),
          el('span', { class: 'photo__ph-hint', text: 'Fotografía pendiente' }),
        ])
      );
    }
    if (p.caption) fig.append(el('figcaption', { text: p.caption }));
    return fig;
  }

  function stampArt(stamp, className) {
    const svg =
      stamp.status === 'ready'
        ? C.art.stamp(stamp.art, `Sello ${pad(stamp.id)}: ${stamp.title}`)
        : C.art.stamp({ shape: 'pending', number: pad(stamp.id) }, `Sello ${pad(stamp.id)}, pendiente`);
    return el('span', { class: className, style: `--rot:${rotation(stamp.id)}deg`, svg });
  }

  function initReveal() {
    document.addEventListener('click', (event) => {
      const trigger = event.target.closest('[data-reveal]');
      if (!trigger) return;
      const target = document.getElementById(trigger.getAttribute('aria-controls'));
      if (!target) return;
      const open = trigger.getAttribute('aria-expanded') !== 'true';
      trigger.setAttribute('aria-expanded', String(open));
      trigger.classList.toggle('is-revealed', open);
      target.hidden = !open;
      const label = trigger.querySelector('[data-reveal-label]');
      if (label && trigger.dataset.labelOpen) {
        label.textContent = open ? trigger.dataset.labelOpen : trigger.dataset.labelClosed;
      }
    });
  }

  function initKeyboardPager() {
    document.addEventListener('keydown', (event) => {
      if (event.defaultPrevented || event.altKey || event.ctrlKey || event.metaKey || event.shiftKey) return;
      if (event.target.closest('input, textarea, select, dialog[open]')) return;
      const dir = event.key === 'ArrowLeft' ? 'prev' : event.key === 'ArrowRight' ? 'next' : null;
      if (!dir) return;
      const control = document.querySelector(`[data-pager="${dir}"]`);
      if (!control || control.disabled) return;
      event.preventDefault();
      control.click();
    });
  }

  function animateIn(node) {
    if (reduceMotion.matches || !node.animate) return;
    node.animate(
      [
        { opacity: 0, transform: 'translateY(6px)' },
        { opacity: 1, transform: 'none' },
      ],
      { duration: 280, easing: 'ease-out' }
    );
  }

  /* ---------- Credential ---------- */

  function slot(id) {
    const stamp = getStamp(id);
    if (stamp.status === 'ready') {
      return el('li', { class: 'slot slot--ready' }, [
        el('a', { class: 'slot__link', href: `stamp.html?id=${id}` }, [
          el('span', { class: 'slot__num', text: pad(id) }),
          stampArt(stamp, 'slot__art'),
          el('span', { class: 'slot__title', text: stamp.title }),
        ]),
      ]);
    }
    return el('li', { class: 'slot slot--pending' }, [
      el('div', { class: 'slot__inner' }, [
        stampArt(stamp, 'slot__art'),
        el('span', { class: 'slot__title', text: 'Pendiente' }),
      ]),
    ]);
  }

  function leaf(index) {
    const ids = C.leaves[index];
    const chapter = chapterOf(ids[0]);
    const titleId = `leaf-${index + 1}-title`;
    return el('article', { class: 'leaf paper', 'aria-labelledby': titleId }, [
      el('header', { class: 'leaf__head' }, [
        el('p', { class: 'kicker', text: chapter.number ? `Capítulo ${chapter.number}` : 'Capítulo' }),
        el('h2', { class: 'leaf__title', id: titleId, text: chapter.title }),
      ]),
      el('ul', { class: 'leaf__grid', 'data-count': String(ids.length) }, ids.map(slot)),
      el('footer', { class: 'leaf__foot', text: String(index + 1) }),
    ]);
  }

  function blankLeaf() {
    return el('article', { class: 'leaf leaf--blank paper', 'aria-label': 'Final de la credencial' }, [
      el('p', { class: 'leaf__end', text: 'Fin de la credencial' }),
    ]);
  }

  function initCredential() {
    const spread = document.getElementById('spread');
    const prev = document.getElementById('pager-prev');
    const next = document.getElementById('pager-next');
    const nextLabel = next.querySelector('[data-label]');
    const status = document.getElementById('pager-status');
    const desktop = window.matchMedia('(min-width: 900px)');
    const total = C.leaves.length;

    const step = () => (desktop.matches ? 2 : 1);
    const normalize = (i) => {
      const clamped = Math.max(0, Math.min(total - 1, i));
      return desktop.matches ? clamped - (clamped % 2) : clamped;
    };

    let current = normalize((parseInt(param('leaf'), 10) || 1) - 1);

    function render(animate) {
      const shown = desktop.matches ? [current, current + 1] : [current];
      spread.replaceChildren(...shown.map((i) => (i < total ? leaf(i) : blankLeaf())));
      C.art.hydrate(spread);

      const isLast = current + step() >= total;
      prev.disabled = current === 0;
      nextLabel.textContent = isLast ? 'Despedida' : 'Siguiente';

      const last = Math.min(current + step(), total);
      status.textContent =
        last - current > 1 ? `Hojas ${current + 1}–${last} de ${total}` : `Hoja ${current + 1} de ${total}`;

      window.history.replaceState(null, '', `?leaf=${current + 1}`);
      if (animate) animateIn(spread);
    }

    prev.addEventListener('click', () => {
      current = normalize(current - step());
      render(true);
    });

    next.addEventListener('click', () => {
      if (current + step() >= total) {
        navigate('farewell.html', true);
        return;
      }
      current = normalize(current + step());
      render(true);
    });

    const onViewportChange = () => {
      current = normalize(current);
      render(false);
    };
    desktop.addEventListener('change', onViewportChange);

    render(false);
    return () => desktop.removeEventListener('change', onViewportChange);
  }

  /* ---------- Stamp index ---------- */

  function initIndex() {
    const root = document.getElementById('index-root');
    const sections = C.chapters.map((chapter, ci) => {
      const headingId = `chapter-${ci + 1}`;
      return el('section', { class: 'index__chapter', 'aria-labelledby': headingId }, [
        el('p', { class: 'kicker', text: `Capítulo ${ROMAN[ci] || ci + 1}` }),
        el('h2', { id: headingId, text: chapter.title }),
        el(
          'ol',
          { class: 'index__list' },
          chapter.stamps.map((id) => {
            const stamp = getStamp(id);
            const content = [
              el('span', { class: 'index__num', text: pad(id) }),
              el('span', { class: 'index__title', text: stamp.title }),
              el('span', { class: 'index__status', text: stamp.status === 'ready' ? 'Abrir' : 'Pendiente' }),
            ];
            return el('li', null, [
              stamp.status === 'ready'
                ? el('a', { class: 'index__item', href: `stamp.html?id=${id}` }, content)
                : el('div', { class: 'index__item is-pending' }, content),
            ]);
          })
        ),
      ]);
    });
    root.replaceChildren(...sections);
  }

  /* ---------- Stamp ---------- */

  function sheetHeader(stamp, titleId, title, subtitle) {
    const chapter = chapterOf(stamp.id);
    return [
      el('p', { class: 'kicker', text: `${chapter.title} · Sello ${pad(stamp.id)}` }),
      el('h1', { class: 'sheet__title', id: titleId, text: title }),
      subtitle ? el('p', { class: 'sheet__subtitle', text: subtitle }) : null,
    ];
  }

  const LAYOUTS = {
    prep(stamp) {
      const titleId = 'stamp-title';
      return el('article', { class: 'sheet paper layout-prep', 'aria-labelledby': titleId }, [
        el('div', { class: 'layout-prep__media' }, [
          photo(stamp.photo, 'photo--print'),
          el('aside', { class: 'diary-note', 'aria-label': stamp.note.label }, [
            el('p', { class: 'kicker', text: stamp.note.label }),
            el('p', { class: 'handwritten', text: stamp.note.text }),
          ]),
        ]),
        el('div', { class: 'layout-prep__text' }, [
          el('header', { class: 'sheet__head' }, [
            stampArt(stamp, 'sheet__stamp'),
            ...sheetHeader(stamp, titleId, stamp.editorialTitle, stamp.title),
          ]),
          el(
            'div',
            { class: 'prose' },
            stamp.text.map((t) => el('p', { text: t }))
          ),
          el('section', { class: 'tips', 'aria-labelledby': 'stamp-tips' }, [
            el('h2', { id: 'stamp-tips', text: stamp.tips.title }),
            el(
              'ul',
              null,
              stamp.tips.items.map((t) => el('li', { text: t }))
            ),
          ]),
        ]),
      ]);
    },

    day(stamp) {
      const titleId = 'stamp-title';
      const storyId = 'stamp-story';
      const secret = stamp.secret;
      return el('article', { class: 'sheet paper layout-day', 'aria-labelledby': titleId }, [
        photo(stamp.hero, 'layout-day__hero'),
        el('header', { class: 'sheet__head layout-day__head' }, [
          stampArt(stamp, 'sheet__stamp'),
          ...sheetHeader(stamp, titleId, stamp.heading),
          el('p', { class: 'sheet__date', text: stamp.date }),
        ]),
        el('div', { class: 'layout-day__body' }, [
          el('section', { class: 'moments', 'aria-labelledby': 'stamp-moments' }, [
            el('h2', { id: 'stamp-moments', text: stamp.moments.title }),
            el(
              'ol',
              null,
              stamp.moments.items.map((t) => el('li', null, [el('p', { text: t })]))
            ),
          ]),
          el('aside', { class: 'layout-day__aside', 'aria-label': 'Datos del día' }, [
            el(
              'dl',
              { class: 'facts' },
              stamp.facts.flatMap((f) => [el('dt', { text: f.label }), el('dd', { text: f.value })])
            ),
            el('div', { class: 'secret' }, [
              photo(secret.photo, 'photo--print'),
              el(
                'button',
                {
                  class: 'btn secret__btn',
                  type: 'button',
                  'data-reveal': true,
                  'aria-expanded': 'false',
                  'aria-controls': storyId,
                  'data-label-open': secret.buttonOpen,
                  'data-label-closed': secret.button,
                },
                [el('span', { 'data-reveal-label': true, text: secret.button })]
              ),
              el('p', { class: 'secret__story handwritten', id: storyId, hidden: true, text: secret.story }),
            ]),
          ]),
        ]),
      ]);
    },
  };

  function pendingSheet(stamp) {
    const titleId = 'stamp-title';
    return el('article', { class: 'sheet paper layout-pending', 'aria-labelledby': titleId }, [
      stampArt(stamp, 'layout-pending__art'),
      ...sheetHeader(stamp, titleId, `Sello ${pad(stamp.id)}`),
      el('p', { class: 'layout-pending__text', text: 'Contenido pendiente' }),
    ]);
  }

  function pagerLink(dir, href, label, detail) {
    return el('a', { class: 'btn', href, rel: dir, 'data-pager': dir }, [
      dir === 'prev' ? el('span', { 'aria-hidden': 'true', text: '←' }) : null,
      el('span', null, [label, detail ? el('small', { text: ` · ${detail}` }) : null]),
      dir === 'next' ? el('span', { 'aria-hidden': 'true', text: '→' }) : null,
    ]);
  }

  function stampPager(id) {
    const leafHref = `credential.html?leaf=${leafOf(id) + 1}`;
    const prev =
      id > 1
        ? pagerLink('prev', `stamp.html?id=${id - 1}`, 'Anterior', `Sello ${pad(id - 1)}`)
        : pagerLink('prev', leafHref, 'Credencial');
    const next =
      id < C.TOTAL_STAMPS
        ? pagerLink('next', `stamp.html?id=${id + 1}`, 'Siguiente', `Sello ${pad(id + 1)}`)
        : pagerLink('next', 'farewell.html', 'Despedida');
    return el('nav', { class: 'pager', 'aria-label': 'Navegación entre sellos' }, [
      prev,
      el('div', { class: 'pager__center' }, [
        el('a', { class: 'btn btn--quiet', href: leafHref, text: 'Volver a la credencial' }),
        el('a', { class: 'btn btn--quiet', href: 'stamp-index.html', text: 'Índice' }),
      ]),
      next,
    ]);
  }

  function initStamp() {
    const root = document.getElementById('stamp-root');
    const id = Number(param('id'));

    if (!Number.isInteger(id) || id < 1 || id > C.TOTAL_STAMPS) {
      root.replaceChildren(
        el('article', { class: 'sheet paper layout-pending', 'aria-labelledby': 'stamp-title' }, [
          el('h1', { class: 'sheet__title', id: 'stamp-title', text: 'Este sello no existe' }),
          el('p', null, [el('a', { href: 'stamp-index.html', text: 'Ir al índice de sellos' })]),
        ])
      );
      return;
    }

    const stamp = getStamp(id);
    const layout = stamp.status === 'ready' ? LAYOUTS[stamp.layout] : null;
    document.title = `Sello ${pad(id)} · ${stamp.title} — Mi Camino de Santiago`;
    root.replaceChildren(layout ? layout(stamp) : pendingSheet(stamp), stampPager(id));
  }

  /* ---------- Album ---------- */

  function initAlbum() {
    const root = document.getElementById('album-root');
    const dialog = document.getElementById('lightbox');
    const stage = document.getElementById('lightbox-stage');

    root.replaceChildren(
      ...C.album.map((cat) =>
        el('section', { class: 'album__cat', 'aria-labelledby': `album-${cat.id}` }, [
          el('h2', { id: `album-${cat.id}`, text: cat.title }),
          el(
            'ul',
            { class: 'album__grid' },
            cat.photos.map((p, i) =>
              el('li', null, [
                el(
                  'button',
                  {
                    class: 'album__item',
                    type: 'button',
                    'data-cat': cat.id,
                    'data-index': String(i),
                    'aria-label': `Ampliar: ${p.alt || p.label || 'fotografía'}`,
                  },
                  [photo(Object.assign({}, p, { caption: null }))]
                ),
              ])
            )
          ),
        ])
      )
    );

    root.addEventListener('click', (event) => {
      const item = event.target.closest('.album__item');
      if (!item || typeof dialog.showModal !== 'function') return;
      const cat = C.album.find((c) => c.id === item.dataset.cat);
      const p = cat && cat.photos[Number(item.dataset.index)];
      if (!p) return;
      stage.replaceChildren(photo(p, 'photo--large'));
      dialog.showModal();
    });

    dialog.addEventListener('click', (event) => {
      if (event.target === dialog || event.target.closest('[data-close]')) dialog.close();
    });
  }

  /* ---------- Init ---------- */

  const PAGES = {
    credential: initCredential,
    index: initIndex,
    stamp: initStamp,
    album: initAlbum,
  };

  let teardown = null;

  function initPage() {
    const page = PAGES[document.body.dataset.page];
    teardown = page ? page() || null : null;
    C.art.hydrate(document);
  }

  /* ---------- Navigation without reload (keeps ambient sound alive) ---------- */

  const pageCache = new Map();

  function isInternalLink(link, event) {
    if (event.defaultPrevented || event.button !== 0) return false;
    if (event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return false;
    if (link.target && link.target !== '_self') return false;
    if (link.hasAttribute('download')) return false;
    const url = new URL(link.href, window.location.href);
    if (url.origin !== window.location.origin) return false;
    if (!/(\.html|\/)$/.test(url.pathname)) return false;
    if (url.pathname === window.location.pathname && url.search === window.location.search && url.hash) return false;
    return true;
  }

  async function fetchPage(url) {
    const key = url.pathname;
    if (!pageCache.has(key)) {
      const response = await fetch(key, { credentials: 'same-origin' });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      pageCache.set(key, await response.text());
    }
    return new DOMParser().parseFromString(pageCache.get(key), 'text/html');
  }

  function swapDocument(doc) {
    if (teardown) teardown();
    teardown = null;

    document.title = doc.title;
    document.body.className = doc.body.className;
    document.body.dataset.page = doc.body.dataset.page || '';

    // Persistent nodes must never be detached: moving an iframe in the DOM reloads it and cuts the sound.
    Array.from(document.body.children).forEach((node) => {
      if (!node.hasAttribute('data-persist')) node.remove();
    });
    const incoming = Array.from(doc.body.children).filter(
      (node) => !node.hasAttribute('data-persist') && node.tagName !== 'SCRIPT'
    );
    document.body.append(...incoming.map((node) => document.adoptNode(node)));
  }

  async function navigate(href, push) {
    const url = new URL(href, window.location.href);
    let doc;
    try {
      doc = await fetchPage(url);
    } catch (err) {
      window.location.href = url.href;
      return;
    }
    if (push) window.history.pushState(null, '', url.href);
    swapDocument(doc);
    initPage();

    window.scrollTo(0, 0);
    const main = document.querySelector('main');
    if (main) {
      main.setAttribute('tabindex', '-1');
      main.focus({ preventScroll: true });
    }
  }

  function initRouter() {
    document.addEventListener('click', (event) => {
      const link = event.target.closest('a[href]');
      if (!link || !isInternalLink(link, event)) return;
      event.preventDefault();
      if (link.hasAttribute('data-start-sound') && C.music) C.music.play();
      navigate(link.href, true);
    });

    window.addEventListener('popstate', () => navigate(window.location.href, false));
  }

  function init() {
    initReveal();
    initKeyboardPager();
    initRouter();
    initPage();
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
